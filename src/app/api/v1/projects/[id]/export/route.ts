import { NextRequest, NextResponse } from 'next/server';
import { ClassroomAuth } from '@/lib/classroom/auth';
import { projectDb } from '@/lib/project/db';
import { zipSync, strToU8 } from 'fflate';

export const runtime = 'nodejs';

export async function GET(req: NextRequest, { params }: { params: Promise<{ id: string }> }) {
  try {
    const user = await ClassroomAuth.authenticateRequest(req);
    if (!user) {
      return NextResponse.json({ error: 'Unauthenticated' }, { status: 401 });
    }

    const { id } = await params;
    const project = await projectDb.getProject(id);

    if (!project) {
      return NextResponse.json({ error: 'Project not found' }, { status: 404 });
    }

    if (project.ownerId !== user.id) {
      return NextResponse.json({ error: 'Forbidden' }, { status: 403 });
    }

    const files = await projectDb.listFilesForProject(id);
    const zipData: Record<string, Uint8Array> = {};

    // Filter sensitive files
    const SENSITIVE_PATTERNS = [
      /^\.env/i,
      /\.git/i,
      /\.DS_Store/i,
      /__MACOSX/i,
      /id_rsa/i,
      /\.pem$/i,
      /\.key$/i,
    ];

    for (const file of files) {
      if (!file.isFolder && file.path) {
        const normalizedPath = file.path.replace(/^\/+/, '');
        if (normalizedPath) {
          const isSensitive = SENSITIVE_PATTERNS.some(pat => pat.test(normalizedPath) || pat.test(file.name));
          if (!isSensitive) {
            zipData[normalizedPath] = strToU8(file.content || '');
          }
        }
      }
    }

    // Include auto-generated README.txt
    const readmeContent = `================================================================================
CORTEX IDE PROJECT EXPORT
================================================================================
Project Name: ${project.name || 'Untitled Project'}
Project ID:   ${project.id}
Language:     ${project.language || 'Multi-language'}
Exported At:  ${new Date().toISOString()}

INSTRUCTIONS:
1. Extract this zip archive into your desired local directory.
2. Ensure you have the appropriate runtime environment installed for ${project.language}.
3. Note: Environment variables and sensitive secrets have been excluded for security.

Generated by Cortex Code Platform (https://cortex-code-platform.cortexbuild1.workers.dev)
================================================================================
`;
    zipData['README.txt'] = strToU8(readmeContent);

    const zipped = zipSync(zipData);

    return new NextResponse(zipped, {
      headers: {
        'Content-Type': 'application/zip',
        'Content-Disposition': `attachment; filename="${project.name || 'project'}.zip"`,
      },
    });
  } catch (error: any) {
    console.error('Project export error:', error);
    return NextResponse.json({ error: 'Internal Server Error' }, { status: 500 });
  }
}
